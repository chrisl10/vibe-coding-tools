#!/usr/bin/env python3
"""v3 local installer and surface sync for this Wasp Nest checkout.

Writes the explicit installed-plugin registry (~/.wasp-nest/installed-plugins.json)
with actual checkout roots, generates the wasp-fleet-index routing skill from
plugins/*/agents frontmatter, deploys the flat home projection (stingers to
~/.agents/skills, ~/.claude/skills, ~/.codex/skills, and ~/.cloudroom/skills),
deploys Drone agents to ~/.claude/agents where that pattern is enabled, and
registers Codex role TOMLs through Core's own hook. --check reports drift only.

Marketplace plugin caches (~/.zcode, ~/.claude plugins) are managed by each
harness installer; this script never writes into them.

Usage:
  python3 tools/sync-wasp-nest.py [--plugins core,chrisl-forged,...]
  python3 tools/sync-wasp-nest.py --check
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
PLUGINS_DIR = REPO_ROOT / "plugins"
HOME = Path.home()
REGISTRY = HOME / ".wasp-nest/installed-plugins.json"
AGENTS_SKILLS = HOME / ".agents/skills"
CLAUDE_SKILLS = HOME / ".claude/skills"
CODEX_HOME = Path(os.environ.get("CODEX_HOME", HOME / ".codex"))
CODEX_SKILLS = CODEX_HOME / "skills"
CLOUDROOM_SKILLS = HOME / ".cloudroom/skills"
CLAUDE_AGENTS = HOME / ".claude/agents"
ZCODE_AGENTS = HOME / ".zcode/agents"
FLEET_INDEX = PLUGINS_DIR / "wasp-nest-core/skills/wasp-fleet-index/SKILL.md"

FLEET_INDEX_HEADER = """---
name: wasp-fleet-index
description: "Auto-generated routing index of every Wasp Nest drone agent ({total} agents). Use it to pick the right specialist and spawn it as a subagent (Cloudroom: room-cli thread spawn or plain words; Claude/ZCode: native agent). Full invocation contracts live in the harness agent registries; the knowledge lives in each drone's matching stinger skill. Regenerated by tools/sync-wasp-nest.py; do not hand-edit."
metadata:
  generated: true
  generator: tools/sync-wasp-nest.py
---

# Wasp Nest drone fleet index

Auto-generated from plugins/*/agents frontmatter: {total} agents across {packs} packs.
On harnesses with a native agent registry (Claude Code, Codex, ZCode) invoke the agent
directly; on harnesses without one (Pi) route with this index and spawn the specialist
as a subagent through the controlling layer.
"""

